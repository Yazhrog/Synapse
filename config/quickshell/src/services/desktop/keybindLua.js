// keybindLua.js — the pure parts of KeybindService: merging the defaults with
// the user's overrides, conflict checks, and the generated SynapseKeybinds.lua
// / .conf. Pure JS, tested by tests/unit/keybind-lua.test.mjs.
//
// A keybind map is { action: { mods: "SUPER + SHIFT", key: "D", label, group } };
// empty mods/key means the action is unbound.

// Defaults + the overrides on disk → the keybind map. Overrides only change
// mods/key of an action the defaults know.
function merge(defaults, overrides) {
    const merged = {}
    for (const k of Object.keys(defaults))
        merged[k] = { mods: defaults[k].mods, key: defaults[k].key,
                      label: defaults[k].label, group: defaults[k].group }
    for (const k of Object.keys(overrides || {})) {
        const o = overrides[k]
        if (!merged[k] || !o) continue
        if (o.mods !== undefined) merged[k].mods = o.mods
        if (o.key  !== undefined) merged[k].key  = o.key
    }
    return merged
}

// The keybind map → what keybinds.json stores: only the binds that differ
// from the defaults.
function overridesOf(keybinds, defaults) {
    const out = {}
    for (const k of Object.keys(keybinds)) {
        if (!defaults[k]) continue
        const b = keybinds[k]
        if (b.mods !== defaults[k].mods || b.key !== defaults[k].key)
            out[k] = { mods: b.mods, key: b.key }
    }
    return out
}

// "SUPER + SHIFT" → Hyprland's modmask integer.
function modsToMask(mods) {
    let mask = 0
    for (const part of mods.toUpperCase().split("+")) {
        const p = part.trim()
        if      (p === "SUPER") mask |= 64
        else if (p === "SHIFT") mask |= 1
        else if (p === "CTRL")  mask |= 4
        else if (p === "ALT")   mask |= 8
    }
    return mask
}

// The Hyprland bind (from `hyprctl binds -j`) that mods + key would collide
// with, as a short description, or "". Submap, mouse and our own shell binds
// (an argument containing "qs ipc") don't count.
function hyprConflict(hyprBinds, mods, key) {
    const mask = modsToMask(mods)
    const k = key.toLowerCase()
    for (const b of hyprBinds) {
        if (b.submap !== "") continue
        if (b.mouse) continue
        if (b.arg && b.arg.indexOf("qs ipc") >= 0) continue
        if (b.modmask === mask && (b.key || "").toLowerCase() === k) {
            let desc = b.dispatcher || ""
            if (b.arg) desc += ": " + b.arg.substring(0, 36)
            return desc || "Hyprland bind"
        }
    }
    return ""
}

// "mods+key" → the actions bound to it (bound actions only).
function comboMap(keybinds) {
    const m = {}
    for (const k of Object.keys(keybinds)) {
        const b = keybinds[k]
        if (!b || !b.mods || !b.key) continue
        const combo = b.mods + "+" + b.key
        m[combo] = (m[combo] || []).concat([k])
    }
    return m
}

// The label of another action already bound to mods + key, or "".
function shellConflict(keybinds, action, mods, key) {
    const combo = mods + "+" + key
    for (const k of Object.keys(keybinds)) {
        if (k === action) continue
        const b = keybinds[k]
        if (b && b.mods + "+" + b.key === combo) return b.label || k
    }
    return ""
}

// Bound actions per group, groups in first-seen order.
function grouped(keybinds) {
    const groups = {}, order = []
    for (const k of Object.keys(keybinds)) {
        const b = keybinds[k]
        if (!b || !b.mods || !b.key) continue
        const g = b.group || "Other"
        if (!groups[g]) { groups[g] = []; order.push(g) }
        groups[g].push({ k: k, mods: b.mods, key: b.key, label: b.label })
    }
    return { groups, order }
}

const RULE = "=============================================================================="

// SynapseKeybinds.lua: the capture submap, then one hl.bind per bound action.
function genLua(keybinds) {
    const data = grouped(keybinds)
    const lines = [
        "-- " + RULE,
        "-- Synapse Keybinds",
        "-- Auto-generated by Quickshell. Do not edit manually.",
        "-- " + RULE,
        "",
        "-- " + RULE,
        "-- Synapse Capture Submap (Disables all normal binds during recording)",
        "-- " + RULE,
        "hl.define_submap(\"Synapse_clean\", function()",
        "    -- Emergency exit in case the shell crashes during capture",
        "    hl.bind(\"CTRL + ESCAPE\", function()",
        "        hl.dispatch(hl.dsp.exec_cmd(\"notify-send 'Synapse' 'Emergency Exit: Keybinds re-enabled.'\"))",
        "        hl.dispatch(hl.dsp.submap(\"reset\"))",
        "    end, { description = \"Emergency return to global submap\" })",
        "end)",
        "",
        "-- " + RULE,
        "-- User Defined Bindings",
        "-- " + RULE,
        ""
    ]
    for (const g of data.order) {
        lines.push("-- " + g)
        // No -c: ~/.config/quickshell is a symlink to the repo, so Synapse is
        // quickshell's "default" config and `qs ipc` finds it on its own.
        for (const e of data.groups[g])
            lines.push("hl.bind(\"" + e.mods + " + " + e.key + "\", hl.dsp.exec_cmd(\"qs ipc call " + e.k + " toggle\"))")
        lines.push("")
    }
    return lines.join("\n")
}

// SynapseKeybinds.conf: the same binds in hyprland.conf syntax.
function genConf(keybinds) {
    const data = grouped(keybinds)
    const lines = [
        "# " + RULE,
        "# Synapse Keybinds",
        "# Auto-generated by Quickshell. Do not edit manually.",
        "# " + RULE,
        "",
        "# " + RULE,
        "# Synapse Capture Submap (Disables all normal binds during recording)",
        "# " + RULE,
        "submap = Synapse_clean",
        "bind = CTRL, ESCAPE, exec, notify-send 'Synapse' 'Emergency Exit: Keybinds re-enabled.'",
        "bind = CTRL, ESCAPE, submap, reset",
        "submap = reset",
        "",
        "# " + RULE,
        "# User Defined Bindings",
        "# " + RULE,
        ""
    ]
    for (const g of data.order) {
        lines.push("# " + g)
        for (const e of data.groups[g]) {
            // The .conf format drops the '+' between modifiers.
            const confMods = e.mods.replace(/\s*\+\s*/g, " ")
            lines.push("bind = " + confMods + ", " + e.key + ", exec, qs ipc call " + e.k + " toggle")
        }
        lines.push("")
    }
    return lines.join("\n")
}

